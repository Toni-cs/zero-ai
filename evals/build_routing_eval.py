def main():
    os.makedirs("evals", exist_ok=True)
    out = os.path.join("evals", "routing_eval.jsonl")
    with io.open(out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    c = Counter(r["gold"] for r in rows)
    tags = Counter(r["tag"] for r in rows)
    lines = [
        "总数: %d" % len(rows),
        "gold分布: " + json.dumps(dict(c), ensure_ascii=False, sort_keys=True),
        "tag分布: " + json.dumps(dict(tags), ensure_ascii=False, sort_keys=True),
    ]
    io.open("evals/_stat.txt", "w", encoding="utf-8").write("\n".join(lines))
    print("written ->", out)


if __name__ == "__main__":
    main()
