def main():
    out = os.path.join("evals", "routing_holdout.jsonl")
    # 与 dev 集文本查重：留出集必须是全新文本
    dev_path = os.path.join("evals", "routing_eval.jsonl")
    dev_texts = set()
    if os.path.exists(dev_path):
        with io.open(dev_path, encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    dev_texts.add(json.loads(line)["text"])
    dup = [r["text"] for r in rows if r["text"] in dev_texts]
    assert not dup, "以下留出集样本与 dev 集重复：%s" % dup

    with io.open(out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    c = Counter(r["gold"] for r in rows)
    t = Counter(r["tag"] or "(常规)" for r in rows)
    print("OK -> %s   n=%d  与dev重复=%d" % (out, len(rows), len(dup)))
    print("gold:", dict(c.most_common()))
    print("tag :", dict(t.most_common()))


if __name__ == "__main__":
    main()
