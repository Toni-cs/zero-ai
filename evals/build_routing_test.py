def main():
    out = os.path.join("evals", "routing_test.jsonl")
    dev = os.path.join("evals", "routing_eval.jsonl")
    hold = os.path.join("evals", "routing_holdout.jsonl")

    seen = set()
    for p in (dev, hold):
        if os.path.exists(p):
            with io.open(p, encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        seen.add(json.loads(line)["text"])

    dups = [r["text"] for r in rows if r["text"] in seen]
    assert not dups, "与 dev/holdout 重复：%s" % dups

    mine = [r["text"] for r in rows]
    assert len(mine) == len(set(mine)), "测试集内部有重复文本"

    with io.open(out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    digest = hashlib.sha256(io.open(out, "rb").read()).hexdigest()
    lock = {"file": out, "n": len(rows), "sha256": digest,
            "rule": "只允许在全部调优完成后跑一次；看过错判明细即作废"}
    os.makedirs("evals/results", exist_ok=True)
    with io.open("evals/results/test_set_lock.json", "w",
                 encoding="utf-8") as f:
        json.dump(lock, f, ensure_ascii=False, indent=2)

    c = Counter(r["gold"] for r in rows)
    t = Counter(r["tag"] or "(常规)" for r in rows)
    print("OK -> %s  n=%d  dup=%d" % (out, len(rows), len(dups)))
    print("sha256 =", digest)
    print("gold:", dict(c.most_common()))
    print("tag :", dict(t.most_common()))


if __name__ == "__main__":
    main()
